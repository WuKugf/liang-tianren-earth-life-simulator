function makeTrees() {
  const out = [];
  // 与连廊/屋面冲突的位置跳过
  const bands = [8, -36, -20.5, 47, 78, -100];
  const busy = (z) => bands.some((b) => Math.abs(z - b) < 4.2);

  // 南北向行道树（东西两侧围墙内）
  for (let z = -138; z <= 138; z += 16) {
    if (!busy(z)) out.push({ x: -146, z, s: 1 }, { x: 146, z, s: 1 });
  }
  // 校门到广场主轴两侧
  for (let z = 60; z <= 104; z += 12) {
    out.push({ x: -14, z, s: 0.9 }, { x: 18, z, s: 0.9 });
  }
  // 教学区内部与连廊旁
  for (let i = 0; i < 3; i++) {
    out.push({ x: -126 + i * 42, z: 2, s: 0.85 });
    out.push({ x: -126 + i * 42, z: -26, s: 0.85 });
  }
  // 操场与球场之间
  for (let x = 30; x <= 132; x += 17) out.push({ x, z: -14, s: 0.8 });
  for (let x = 30; x <= 126; x += 16) out.push({ x, z: -86, s: 0.8 });
  // 体育馆周围
  out.push({ x: 96, z: -92, s: 1 }, { x: 130, z: -92, s: 1 }, { x: 96, z: -138, s: 1 }, { x: 130, z: -138, s: 1 });
  return out;
}

export const TREES = makeTrees();

